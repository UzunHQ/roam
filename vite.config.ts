import { defineConfig, type Plugin } from 'vite';
import { readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

/**
 * Writes dist/sw.js with a precache list of everything in the build:
 * app shell, hashed JS/CSS, places.json, campus.geojson, icons and photos.
 */
function serviceWorker(): Plugin {
  return {
    name: 'roam-sw',
    apply: 'build',
    generateBundle(_, bundle) {
      const publicFiles = walk('public').map((p) => relative('public', p).split('\\').join('/')).filter((p) => !p.split('/').pop()!.startsWith('.'));
      const files = ['/', ...Object.keys(bundle).filter((f) => f !== 'picker.html'), ...publicFiles].map((f) => (f.startsWith('/') ? f : '/' + f));
      // Installed up front: the app shell, its data and the small icons. Left out: the map files
      // (MapLibre, its worker, our map style: cached the first time they're used, and never
      // fetched at all by a browser without WebGL), the large install icons and the share image.
      // Precache requests are served from the HTTP cache the page has just filled, so nothing in
      // this list downloads twice.
      const LATER = [/\/assets\/maplibre/, /\/assets\/map-/, /maplibre-gl-worker/, /^\/og\.jpg$/, /icon-512\.png$/, /icon-maskable-512\.png$/, /apple-touch-icon\.png$/];
      const precache = files.filter((f) => f !== '/index.html' && !LATER.some((re) => re.test(f)));
      const version = createHash('sha1').update(files.join('|') + Object.values(bundle).map((b) => ('code' in b ? b.code : String(b.source))).join('')).digest('hex').slice(0, 10);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// generated by vite.config.ts
const CACHE = 'roam-${version}';
const PRECACHE = ${JSON.stringify(precache)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('roam-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return; // analytics etc. go straight to network
  if (req.mode === 'navigate') {
    // /?place=id and friends all get the cached app shell
    e.respondWith(fetch(req).catch(() => caches.match('/', { cacheName: CACHE, ignoreVary: true })));
    return;
  }
  e.respondWith(
    caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
      return res;
    })),
  );
});
`,
        });
    },
  };
}

export default defineConfig({
  plugins: [serviceWorker()],
  build: {
    target: 'es2022',
    chunkSizeWarningLimit: 1100, // maplibre-gl is ~1 MB raw (about 250 KB compressed) on its own
    assetsInlineLimit: 0,
    rollupOptions: {
      input: { main: 'index.html' }, // picker.html is dev-only
      // MapLibre in a file of its own: it changes far less often than Roam, so it stays cached across updates
      output: { manualChunks: (id) => (id.includes('node_modules/maplibre-gl') ? 'maplibre' : undefined) },
    },
  },
});
